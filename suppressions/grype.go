package suppressions

import (
	"bytes"
	"encoding/json"
	"fmt"
	"regexp"
	"sort"
	"strings"

	"github.com/deathlabs/finch/models"
)

const (
	// GrypeIgnoreFileName is a Grype config file holding only ignore rules. Pass it using --config.
	GrypeIgnoreFileName = "grype-ignore.yaml"
	// GrypeReportFileName records why each vulnerability is suppressed.
	GrypeReportFileName = "grype-suppression-report.json"

	grypeToolName = "Grype"
)

// grypeVulnerabilityID matches vulnerability IDs such as CVE-2021-44228 and
// GHSA-jfh8-c2jp-5v3q. IDs are written into a YAML file, so only letters,
// digits, dots, underscores, and hyphens are allowed.
var grypeVulnerabilityID = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{2,62}$`)

// generateGrype builds the Grype suppression files from the components in document.
func generateGrype(document models.ExportDocument, options Options) (Result, error) {
	var (
		err        error
		ignoreData []byte
		reportData []byte
		rules      []reportSuppression
	)

	rules, err = collectGrypeRules(document)
	if err != nil {
		return Result{}, err
	}

	ignoreData = renderGrypeIgnore(rules)

	reportData, err = json.MarshalIndent(report{
		Tool:         grypeToolName,
		FinchVersion: options.FinchVersion,
		Mappings:     document.Metadata,
		Suppressions: rules,
	}, "", "  ")
	if err != nil {
		return Result{}, fmt.Errorf("could not build the suppression report: %w", err)
	}
	reportData = append(reportData, '\n')

	return Result{
		Files: []File{
			{Name: GrypeIgnoreFileName, Content: ignoreData},
			{Name: GrypeReportFileName, Content: reportData},
		},
		RuleCount: len(rules),
	}, nil
}

// collectGrypeRules gathers every Grype vulnerability ID mapped to a component,
// merging components that mitigate the same vulnerability, in sorted order.
func collectGrypeRules(document models.ExportDocument) ([]reportSuppression, error) {
	var (
		byID      = map[string]*reportSuppression{}
		component models.ComponentDefinition
		id        string
		ids       []string
		ok        bool
		rawRule   string
		rules     []reportSuppression
		toolRules models.ToolRules
		entry     *reportSuppression
	)

	for _, component = range document.Components {
		for _, toolRules = range component.SecurityRulesMitigatedByThisComponent {
			if !strings.EqualFold(strings.TrimSpace(toolRules.Tool), grypeToolName) {
				continue
			}

			for _, rawRule = range toolRules.Rules {
				id = strings.TrimSpace(rawRule)
				if !grypeVulnerabilityID.MatchString(id) || !strings.Contains(id, "-") {
					return nil, fmt.Errorf("component %q: %q is not a valid vulnerability ID", component.Title, rawRule)
				}

				// A suppression must cite the platform control that backs it.
				if len(component.ControlsImplementedByThisComponent) == 0 {
					return nil, fmt.Errorf("component %q maps Grype vulnerability %s but implements no controls, so there is nothing to cite", component.Title, id)
				}

				// CVE IDs are case-insensitive, so normalize them.
				if strings.HasPrefix(strings.ToUpper(id), "CVE-") {
					id = strings.ToUpper(id)
				}

				entry, ok = byID[id]
				if !ok {
					entry = &reportSuppression{RuleID: id}
					byID[id] = entry
					ids = append(ids, id)
				}

				if !hasComponent(entry.Components, component.UUID, component.Title) {
					entry.Components = append(entry.Components, reportComponent{
						Title:    component.Title,
						UUID:     component.UUID,
						Controls: append([]string(nil), component.ControlsImplementedByThisComponent...),
					})
				}
			}
		}
	}

	sort.Strings(ids)
	rules = make([]reportSuppression, 0, len(ids))
	for _, id = range ids {
		rules = append(rules, *byID[id])
	}
	return rules, nil
}

// renderGrypeIgnore renders a Grype config holding one ignore rule per
// vulnerability. A rule with only a vulnerability ID matches that vulnerability
// in every package.
func renderGrypeIgnore(rules []reportSuppression) []byte {
	var (
		buffer bytes.Buffer
		rule   reportSuppression
	)

	buffer.WriteString("# Generated by Finch. Do not edit.\n")
	buffer.WriteString("# Vulnerabilities mitigated by the deployment platform. See grype-suppression-report.json.\n")
	if len(rules) == 0 {
		buffer.WriteString("ignore: []\n")
		return buffer.Bytes()
	}
	buffer.WriteString("ignore:\n")
	for _, rule = range rules {
		fmt.Fprintf(&buffer, "  - vulnerability: %q\n", rule.RuleID)
	}
	return buffer.Bytes()
}
